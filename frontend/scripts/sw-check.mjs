import { chromium } from '@playwright/test'
const b = await chromium.launch(); const ctx = await b.newContext(); const page = await ctx.newPage()
const r = await page.request.post('http://127.0.0.1:8000/api/v1/auth/login', { data: { email: 'admin@eventflow.test', password: 'password' } }); const s = await r.json()
await page.goto('http://127.0.0.1:4173/login', { waitUntil: 'domcontentloaded' })
await page.evaluate((x) => { localStorage.setItem('ef_token', x.token); localStorage.setItem('ef_user', JSON.stringify(x.user)) }, s)
await page.goto('http://127.0.0.1:4173/clients', { waitUntil: 'load' })
await page.locator('table tbody tr:visible, .record-card:visible').first().waitFor({ timeout: 30000 })
await page.waitForTimeout(1500)
const reg = await page.evaluate(async () => { const r = await navigator.serviceWorker.getRegistration(); return !!(r && (r.active || r.waiting || r.installing)) })
console.log('sw registered', reg)
await page.reload({ waitUntil: 'load' }); await page.waitForTimeout(1000)
await ctx.setOffline(true)
await page.reload({ waitUntil: 'domcontentloaded' })
await page.locator('table tbody tr:visible, .record-card:visible').first().waitFor({ timeout: 15000 })
console.log('offline reload shows cached list; banner:', await page.getByText('You are offline').count())
await page.screenshot({ path: '/downloads/offline-check.png' })
await b.close()
